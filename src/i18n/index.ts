/* ───────────────────────── runtime state ───────────────────────── */

let current: Lang = 'zh';
const listeners = new Set<() => void>();

function readStored(): Lang {
  try {
    const v = localStorage.getItem(LS_LANG);
    if (v === 'en' || v === 'zh') return v;
  } catch {
    /* storage may be unavailable */
  }
  return 'zh';
}

/** Read the persisted language (called once at boot). */
export function initLang(): Lang {
  current = readStored();
  document.documentElement.lang = current === 'en' ? 'en' : 'zh-CN';
  return current;
}

export function getLang(): Lang {
  return current;
}

/**
 * Switch language, persist it, update `<html lang>`, and notify subscribers
 * (the App rebuilds its UI in response).
 */
export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  try {
    localStorage.setItem(LS_LANG, lang);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
  for (const fn of listeners) fn();
}

export function onLangChange(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    k in params ? String(params[k]) : `{${k}}`
  );
}

/** Translate a key for the current language, with optional interpolation. */
export function t(key: string, params?: Record<string, string | number>): string {
  const dict = current === 'en' ? en : zh;
  const template = dict[key] ?? zh[key] ?? key;
  return interpolate(template, params);
}

/**
 * Refresh every element carrying a `data-i18n="key"` attribute (used for the
 * static markup in `index.html`) and the document title. Call after boot and
 * after every language change.
 */
export function applyPageI18n(root: ParentNode = document): void {
  document.title = t('app.title');
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });
}
